#!/usr/bin/env node
// services/occt/build/extract-methods.mjs
//
// Deeper scan than extract-symbols.mjs: for the Option C hand-written
// Embind build we need to know, per OCCT class, WHICH constructor
// overloads and static members the code actually calls — that is the
// precise spec of what the bindings must register. Emscripten/embind
// exposes each C++ overload as `Class_N` / `method_N`, and our code
// calls those suffixed names directly (e.g. `new oc.gp_Pnt_3(...)`,
// `oc.TopoDS.Face_1(...)`, `oc.BRep_Tool.Triangulation(...)`), so the
// suffixes are statically visible even though instance-method calls on
// typed variables are not.
//
// Usage:
//   node services/occt/build/extract-methods.mjs          # summary
//   node services/occt/build/extract-methods.mjs --spec   # emit BINDINGS_SPEC.md
//
// What it CAN see (statically, reliably):
//   - constructor overloads:      new oc.<Class>_<N>(...)
//   - static / namespaced members: oc.<Class>.<Member>[_<N>](...)
// What it CANNOT see (needs a human reading the code):
//   - instance methods on typed vars (const f = ...; f.Orientation_1())
//     — reported only as a global best-effort name list.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const srcRoot = resolve(__dirname, '../../../src/cad');
const specPath = resolve(__dirname, 'embind/BINDINGS_SPEC.md');

const NOT_A_BINDING = new Set(['FS', 'OCJS', 'Transformation']);

function walk(dir) {
    const out = [];
    for (const name of readdirSync(dir)) {
        const p = join(dir, name);
        const st = statSync(p);
        if (st.isDirectory()) out.push(...walk(p));
        else if (name.endsWith('.ts') || name.endsWith('.tsx')) out.push(p);
    }
    return out;
}

// `oc.Ns.Member` (static / namespaced) — capture namespace + member.
const STATIC = /(?:oc|instance)\.([A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)*)\.([A-Za-z][A-Za-z0-9_]*)/g;
// `new oc.Class_N(` — constructor overloads.
const CTOR = /\bnew\s+(?:oc|instance)\.([A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)*)\s*\(/g;
// best-effort instance method names: `.Method(` / `.Method_N(`
const METHOD = /\.([A-Z][A-Za-z0-9]*(?:_\d+)?)\s*\(/g;

// A class name is Package_Class (has `_` and an uppercase somewhere) or a
// PascalCase namespace. Split a captured `X_N` into {class, overload}.
function splitOverload(token) {
    const m = token.match(/^(.*?)_(\d+)$/);
    if (m && !/^[a-z]/.test(token.slice(0, 1)) === false) {
        // token like gp_Pnt_3 -> base gp_Pnt, overload 3
    }
    if (m) return { base: m[1], n: m[2] };
    return { base: token, n: null };
}

const ctorOverloads = new Map(); // class -> Set(overloadNums|'0')
const staticMembers = new Map(); // class -> Set(member)
const methodNames = new Map(); // name -> count

for (const file of walk(srcRoot)) {
    const text = readFileSync(file, 'utf8');
    let m;
    while ((m = CTOR.exec(text)) !== null) {
        const { base, n } = splitOverload(m[1]);
        if (NOT_A_BINDING.has(base)) continue;
        if (!ctorOverloads.has(base)) ctorOverloads.set(base, new Set());
        ctorOverloads.get(base).add(n ?? '0');
    }
    while ((m = STATIC.exec(text)) !== null) {
        const cls = m[1];
        const member = m[2];
        if (NOT_A_BINDING.has(cls)) continue;
        // Skip lowercase members (js props like .delete, .get) and the
        // handle-deref `.get`.
        if (/^[a-z]/.test(member)) continue;
        if (!staticMembers.has(cls)) staticMembers.set(cls, new Set());
        staticMembers.get(cls).add(member);
    }
    while ((m = METHOD.exec(text)) !== null) {
        methodNames.set(m[1], (methodNames.get(m[1]) ?? 0) + 1);
    }
}

const classes = [...new Set([...ctorOverloads.keys(), ...staticMembers.keys()])].sort();

if (process.argv.includes('--spec')) {
    const lines = [];
    lines.push('# OCCT Embind binding spec (generated)');
    lines.push('');
    lines.push(
        'Generated by `extract-methods.mjs --spec`. For each OCCT class the',
    );
    lines.push(
        'code touches, this lists the constructor overloads and static /',
    );
    lines.push(
        'namespaced members that appear statically in `src/cad`. Instance',
    );
    lines.push(
        'methods on typed variables are NOT listed here (see the global',
    );
    lines.push('method-name list at the bottom) — bind them by reading the call sites.');
    lines.push('');
    lines.push('> Do not edit by hand — regenerate.');
    lines.push('');
    for (const cls of classes) {
        lines.push(`## ${cls}`);
        const ctors = ctorOverloads.get(cls);
        if (ctors && ctors.size) {
            const list = [...ctors].sort().map((n) => (n === '0' ? '(unnumbered)' : `_${n}`));
            lines.push(`- constructors: ${list.join(', ')}`);
        }
        const statics = staticMembers.get(cls);
        if (statics && statics.size) {
            lines.push(`- static/namespaced: ${[...statics].sort().join(', ')}`);
        }
        lines.push('');
    }
    lines.push('## Global method names invoked (best-effort, all receivers)');
    lines.push('');
    lines.push(
        'Includes non-OCCT calls; use as a checklist of instance methods to',
    );
    lines.push('register on the relevant classes.');
    lines.push('');
    const names = [...methodNames.entries()].sort((a, b) => b[1] - a[1]);
    lines.push(names.map(([n, c]) => `${n} (${c})`).join(', '));
    lines.push('');
    writeFileSync(specPath, lines.join('\n'));
    console.log(`wrote ${specPath} — ${classes.length} classes`);
    process.exit(0);
}

console.log(`Classes with statically-visible ctor/static usage: ${classes.length}`);
console.log(`Distinct instance-method names (best-effort): ${methodNames.size}`);
console.log('');
for (const cls of classes) {
    const ctors = ctorOverloads.get(cls);
    const statics = staticMembers.get(cls);
    const parts = [];
    if (ctors?.size) parts.push(`ctors[${[...ctors].sort().join(',')}]`);
    if (statics?.size) parts.push(`static{${[...statics].sort().join(',')}}`);
    console.log(`  ${cls}: ${parts.join(' ')}`);
}
